CREATE TABLE IF NOT EXISTS demo_meta (id INT PRIMARY KEY, revision BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS catalog (
  sku VARCHAR(48) PRIMARY KEY, label VARCHAR(96) NOT NULL, pack_size INT NOT NULL CHECK(pack_size>0)
);
CREATE TABLE IF NOT EXISTS inventory (
  sku VARCHAR(48) PRIMARY KEY REFERENCES catalog(sku), quantity INT NOT NULL CHECK(quantity>=0),
  data_date DATE NOT NULL, source_name VARCHAR(64) NOT NULL, last_run_id VARCHAR(48)
);
CREATE TABLE IF NOT EXISTS sync_run (
  run_id VARCHAR(48) PRIMARY KEY, task_key VARCHAR(128) UNIQUE NOT NULL,
  status VARCHAR(16) NOT NULL CHECK(status IN ('RUNNING','SUCCEEDED','FAILED')),
  mode VARCHAR(16) NOT NULL, actor VARCHAR(32) NOT NULL, scenario VARCHAR(32) NOT NULL,
  parent_run_id VARCHAR(48), reason VARCHAR(240) NOT NULL,
  business_date DATE NOT NULL, requested_at VARCHAR(48) NOT NULL, finished_at VARCHAR(48),
  source_digest VARCHAR(64), result_json CLOB NOT NULL, error_code VARCHAR(48), error_message VARCHAR(240),
  preview_id VARCHAR(48) UNIQUE NOT NULL
);
CREATE TABLE IF NOT EXISTS audit_event (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, run_id VARCHAR(48),
  actor VARCHAR(32) NOT NULL, action VARCHAR(48) NOT NULL,
  occurred_at VARCHAR(48) NOT NULL, detail_json CLOB NOT NULL
);
CREATE TABLE IF NOT EXISTS baseline_sample (
  sample_key VARCHAR(128) PRIMARY KEY, row_count INT NOT NULL, total_units BIGINT NOT NULL, origin VARCHAR(24) NOT NULL,
  sample_order BIGINT GENERATED BY DEFAULT AS IDENTITY
);
